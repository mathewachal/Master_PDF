import os
from fastapi import APIRouter, HTTPException, Query
from fastapi.responses import FileResponse
from app.jobs.store import job_store
from app.core.cleanup import purge_job_directory

router = APIRouter(prefix="/jobs", tags=["Async Jobs"])


@router.get("/{job_id}")
def get_job_status(job_id: str):
    """Retrieve current progress and state for an asynchronous job."""
    job = job_store.get(job_id)
    if not job:
        raise HTTPException(status_code=404, detail="Job not found")
    
    return {
        "id": job.id,
        "tool_name": job.tool_name,
        "status": job.status,
        "progress": job.progress,
        "message": job.message,
        "created_at": job.created_at,
        "completed_at": job.completed_at,
        "has_output": bool(job.output_path and os.path.exists(job.output_path)),
        "output_filename": job.output_filename,
        "error": job.error,
    }


@router.get("/{job_id}/download")
def download_job_output(job_id: str, purge_after: bool = Query(default=False)):
    """Download the output document generated by a completed job."""
    job = job_store.get(job_id)
    if not job:
        raise HTTPException(status_code=404, detail="Job not found")
    
    if not job.output_path or not os.path.exists(job.output_path):
        raise HTTPException(status_code=404, detail="Job output not available or expired")
    
    response = FileResponse(
        path=job.output_path,
        filename=job.output_filename or "document.pdf",
        media_type="application/octet-stream"
    )

    if purge_after:
        purge_job_directory(job_id)
        job_store.remove(job_id)

    return response


@router.delete("/{job_id}")
def cancel_or_delete_job(job_id: str):
    """Cancel job and immediately delete associated files."""
    job = job_store.get(job_id)
    if not job:
        raise HTTPException(status_code=404, detail="Job not found")
    
    purge_job_directory(job_id)
    job_store.remove(job_id)
    return {"status": "success", "message": f"Job {job_id} deleted and files purged"}
